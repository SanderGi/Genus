"""Emit BoundaryData.lean. Run from any directory with Python 3.10 or later.

The repository constructor proposes witnesses. Lean verifies each proposal on
the fixed boundary model, including mask membership and transfer parity.
"""
from itertools import product
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from kneser_constructor import (  # noqa: E402
    CANDIDATES, Ps, Reduced, _boundary_paths, _one_cycle, p_sign,
)


def witness_words(case):
    boundary = Reduced(41, case, 0)
    transfers = [
        [(i, j, list(p) + [3 + x for x in r])
         for (i, p), (j, r) in product(enumerate(Ps), repeat=2)
         if p_sign(p) * p_sign(r) == (-1) ** bit]
        for bit in (0, 1)
    ]
    for chars in range(1 << len(boundary.outside)):
        for mask in CANDIDATES[case]:
            paths = _boundary_paths(boundary, chars, mask)
            if paths is None:
                continue
            for p, r, transfer in transfers[chars.bit_count() % 2]:
                if _one_cycle([paths[x] for x in transfer]):
                    yield 64 * mask + 8 * p + r
                    break
            else:
                continue
            break
        else:
            raise ValueError((case, chars))


def combine(names):
    """The balanced proof term joins adjacent intervals of character masks."""
    if len(names) == 1:
        return names[0]
    mid = len(names) // 2
    return f'(covered_append {combine(names[:mid])} {combine(names[mid:])})'


print("""import KneserConstruction.BoundaryCheck

/-!
Witnesses for Proposition 7.3 generated by boundary_witness.py.
Each hexadecimal literal stores 256 proposals in increasing pattern order,
least significant first. In each 16-bit proposal the low three bits select
the negative transfer, the next three the positive transfer, and the rest the mask.
-/

namespace BipartiteKneser.Boundary

-- Keep the hexadecimal certificate blocks as single numeric literals.
set_option linter.style.longLine false
set_option maxRecDepth 8192
""")
for case, label in [(1, 'one'), (2, 'two')]:
    words = list(witness_words(case))
    names = []
    for start in range(0, len(words), 256):
        block = sum(x << (16 * i) for i, x in enumerate(words[start:start + 256]))
        name = f'{label}_{start}'
        names.append(name)
        print(f'private theorem {name} : Covered .{label} {start} 256 :=')
        print(f'  covered_of_check _ _ {hex(block)} _ (by decide +kernel)\n')
    print(f'theorem {label}_covered : Covered .{label} 0 {len(words)} :=')
    print(f'  {combine(names)}\n')
print('end BipartiteKneser.Boundary')
